def material_of(mesh):
    mesh = "uf" + mesh[mesh.index("_"):] if mesh.startswith(PINKY_PREFIX + "_") else mesh
    if "pad" in mesh:
        return "uf_pad"
    if "shell" in mesh:
        return "uf_shell"
    if "pin" in mesh:
        return "uf_pin"
    if mesh == "uf_l2":
        return "uf_coupler"
    if mesh == "uf_link":
        return "uf_link"
    return "uf_core2" if mesh == "uf_p2" else "uf_core"


def density(mesh):
    return TPU if ("shell" in mesh or "pad" in mesh) else STEEL if "pin" in mesh else PLA


PINKY_PREFIX = "ufpk"   # meshes of the shorter pinky variant (cad/.../ultimate_finger --scale): ufpk_p1, ...


def stl(mesh):
    if mesh.startswith(PINKY_PREFIX + "_"):
        sfx = PINKY["suffix"]
        return CAD / "stl" / f"{MESHES['uf' + mesh[len(PINKY_PREFIX):]]}{sfx}.stl"
    return CAD / "stl" / f"{(MESHES | THUMB_MESHES)[mesh]}.stl"


PINKY = dict(scale=1.0, suffix="")


def body_meshes(prefix):
    return {k: [prefix + m[2:] for m in v] for k, v in BODY_MESHES.items()}


def fmt(v):
    return " ".join(f"{x:.9g}" for x in np.asarray(v, float).ravel())


def load_design(suffix=""):
    d = json.loads((CAD / f"design{suffix}.json").read_text())
    dz = Design(d["geometry"]["L1"], d["geometry"]["L2"], d["geometry"]["L3_tip"], d["geometry"]["P4"], d["geometry"]["A"],
                d["geometry"]["B"], np.radians(d["drive"]["psi_straight_deg"]), d["geometry"]["tip"][1])
    return d, dz


# ---------------------------------------------------------------- one finger -> ultimate finger (in place)
def convert_finger(mj, link, N, design, dz, suffix="", prefix="uf"):
    gimbal = next(b for b in link if b.tag == "body" and any(g.get("mesh") == "gimbal" for g in b.iter("geom")))
    distal = next(b for b in link if b.tag == "body" and any(g.get("mesh") == "distal" for g in b.findall("geom")))
    mm = 1e-3

    def P(yz, x=0.0):
        return np.array([x, yz[0], yz[1]]) * mm

    lg = next(g for g in link if g.tag == "geom" and g.get("mesh") == "link")
    T_lb_lcad = BF.get_pose(lg)
    gg = next(g for g in gimbal if g.tag == "geom" and g.get("mesh") == "gimbal")
    T_lb_gcad = BF.get_pose(gimbal) @ BF.get_pose(gg)
    T_g_l = Hinv(T_lb_gcad) @ T_lb_lcad
    psi_export = xangle(T_g_l[:3, :3])
    OL3 = P([0.0, -6.0])
    assert np.allclose(T_g_l[:3, :3], flex(psi_export), atol=1e-5), "Link is not a pure rotation about x"
    dx = T_g_l[:3, 3] - (OL3 - flex(psi_export) @ OL3)
    assert abs(dx[1]) < 2e-6 and abs(dx[2]) < 2e-6 and abs(dx[0] * 1e3 - 0.35) < 1e-3, dx
    DX = H(np.eye(3), np.array([dx[0], 0, 0]))   # every new part is drawn on the Link mid-plane
    sol = dz.solve_psi(psi_export)
    th1, th2, th3, l2r = sol["mcp"], sol["pip"], sol["dip"], sol["l2"]

    def about(R, pivot_straight, pivot_now):
        return H(R, pivot_now - R @ pivot_straight)

    T_g = dict(p1=DX @ H(flex(th1)))
    T_g["p2"] = about(flex(th1 + th2), P(dz.PIP0), (T_g["p1"] @ np.r_[P(dz.PIP0), 1])[:3])
    T_g["p3"] = about(flex(th1 + th2 + th3), P(dz.DIP0), (T_g["p2"] @ np.r_[P(dz.DIP0), 1])[:3])
    T_g["l2"] = about(flex(th1 + l2r), P(dz.A0), (T_g["p1"] @ np.r_[P(dz.A0), 1])[:3])
    P4L = np.array(design["geometry"]["P4_in_link_frame"])
    e_p4 = np.linalg.norm((T_g_l @ np.r_[P(P4L), 1])[:3] - (T_g["p2"] @ np.r_[P(dz.P4_0), 1])[:3])
    e_b = np.linalg.norm((T_g["l2"] @ np.r_[P(dz.B0), 1])[:3] - (T_g["p3"] @ np.r_[P(dz.B0), 1])[:3])
    assert e_p4 < 1e-7 and e_b < 1e-7, (e_p4, e_b)

    lg.set("mesh", f"{prefix}_link")
    lg.set("material", "uf_link")
    link.remove(link.find("inertial"))
    studs = 0.5 * (0.00277119 - 0.0019275)   # stock Link body mass minus the stock Link part = ball studs + screws
    items = [BF.mesh_item(stl(f"{prefix}_link"), PLA, T_lb_lcad)]
    for sx in (-8.05, 8.05):
        items.append((studs, (T_lb_lcad @ np.r_[P([3.596, -11.051], sx), 1])[:3], np.eye(3) * 1e-10))
    BF.add_inertial(link, items)
    for c in [c for c in link if BF.is_comment(c) and "parallel_pin_2_x_10" in (c.text or "")]:
        link.remove(c)
    link.remove(distal)

    bm = body_meshes(prefix)

    def add_geoms(body, key):
        for mesh in bm[key]:
            ET.SubElement(body, "geom", {"class": "visual", "type": "mesh", "mesh": mesh, "material": material_of(mesh)})

    link.append(ET.Comment(f" ultimate finger{N}: P2 (middle) on the Link at P4, P1 (proximal) on P2 at the PIP, L2 (DIP "
                           f"coupler) on P1 at A, P3 (distal) on P2 at the DIP; cad/five_finger/ultimate_finger "))
    p2 = ET.SubElement(link, "body", name=f"p2{suffix}")
    BF.set_pose(p2, T_lb_gcad @ T_g["p2"])
    ET.SubElement(p2, "joint", name=f"passive4 ({N})", type="hinge", axis="1 0 0", pos=fmt(P(dz.P4_0)))
    add_geoms(p2, "p2")
    p1 = ET.SubElement(p2, "body", name=f"p1{suffix}")
    BF.set_pose(p1, Hinv(T_g["p2"]) @ T_g["p1"])
    # PIP and DIP stops just beyond the kinematic range (PIP -20.5..78.1, DIP -16.8..54.4 over the whole servo
    # travel). The DIP coupler's four-bar has its branch point at PIP ~ -27 deg: the rigid loop 1 never gets there, but
    # the soft loop closures of the sim can overshoot during abrupt full-range command steps and flip loop 2 (DIP ~ -72)
    # without the stops. In hardware: hyperextension stop faces (see README, risks).
    # joint qpos is measured from the export pose (qpos = 0): PIP joint (P1 in P2, +x) = PIP - PIP_export, DIP joint
    # (P3 in P2, +x) = DIP_export - DIP (flexion is a rotation about -x)
    pip_q = np.radians(PIP_RANGE) - th2
    dip_q = th3 - np.radians(DIP_RANGE)[::-1]
    ET.SubElement(p1, "joint", name=f"passive_5 ({N})", type="hinge", axis="1 0 0", pos=fmt(P(dz.PIP0)),
                  range=fmt(pip_q))
    add_geoms(p1, "p1")
    T_p1cad_gb = Hinv(DX) @ Hinv(BF.get_pose(gg))
    for end in ("", "_z"):
        p_cad = (T_p1cad_gb @ np.r_[BF.get_pose(BF.child(gimbal, "site", f"closing_3 ({N})_2{end}"))[:3, 3], 1])[:3]
        ET.SubElement(p1, "site", name=f"closing_3 ({N})_1{end}", pos=fmt(p_cad), group="3")
    l2 = ET.SubElement(p1, "body", name=f"l2{suffix}")
    BF.set_pose(l2, Hinv(T_g["p1"]) @ T_g["l2"])
    ET.SubElement(l2, "joint", name=f"coupler_a ({N})", type="hinge", axis="1 0 0", pos=fmt(P(dz.A0)))
    add_geoms(l2, "l2")
    ET.SubElement(l2, "site", name=f"closing_dip ({N})_1", pos=fmt(P(dz.B0)), group="3")
    p3 = ET.SubElement(p2, "body", name=f"p3{suffix}")
    BF.set_pose(p3, Hinv(T_g["p2"]) @ T_g["p3"])
    ET.SubElement(p3, "joint", name=f"dip ({N})", type="hinge", axis="1 0 0", pos=fmt(P(dz.DIP0)),
                  range=fmt(dip_q))
    add_geoms(p3, "p3")
    ET.SubElement(p3, "site", name=f"closing_dip ({N})_2", pos=fmt(P(dz.B0)), group="3")
    ET.SubElement(p3, "site", name=f"tip{N}", pos=fmt(P(dz.TIP0)), group="3")
    for body, key in ((p1, "p1"), (p2, "p2"), (p3, "p3"), (l2, "l2")):
        BF.add_inertial(body, [BF.mesh_item(stl(m), density(m)) for m in bm[key]])
    mj.find("equality").append(ET.Element("connect", site1=f"closing_dip ({N})_1", site2=f"closing_dip ({N})_2"))
    return np.degrees([psi_export, th1, th2, th3])


def add_materials(asset):
    have = {m.get("name") for m in asset.findall("material")}
    for name, rgba in MATERIALS.items():
        if name not in have:
            ET.SubElement(asset, "material", name=name, rgba=rgba)


# ---------------------------------------------------------------- single finger
def write_model(mj, name):
    tree = ET.ElementTree(mj)
    ET.indent(tree, space="  ")
    path = MODEL_DIR / f"finger_{name}.xml"
    tree.write(path)
    BF.write_scene(name, path.name, MODEL_DIR)
    q, e = BF.settle_keyframe(MODEL_DIR / f"scene_{name}.xml")
    BF.write_scene(name, path.name, MODEL_DIR, keyframe=q)
    return path, e


def build_stock():
    mj = BF.extract_stock()
    BF.finish_assets(mj, MODEL_DIR)
    path, e = write_model(mj, "stock")
    print(f"wrote {path.relative_to(REPO)} + scene_stock.xml (stock baseline, keyframe loop error {e * 1e3:.4f} mm)")


def build_finger(design, dz):
    mj = BF.extract_stock()
    mj.set("model", "ah_finger_uf")
    mj[0].text = (" Generated by Demo/AHSimulation/ultimate_finger/build_models.py: the index finger of AH_Right_5F with the "
                  "thin styled 3-phalanx finger of cad/five_finger/ultimate_finger. Do not edit by hand. ")
    link = next(b for b in mj.iter("body") if b.get("name") == "rotule_ball")
    ang = convert_finger(mj, link, 1, design, dz)
    BF.finish_assets(mj, MODEL_DIR, [dict(name=k, file=stl(k)) for k in MESHES])
    add_materials(mj.find("asset"))
    path, e = write_model(mj, "uf")
    print(f"wrote {path.relative_to(REPO)} + scene_uf.xml (export pose: Link {ang[0]:.2f}, MCP {ang[1]:.2f}, PIP {ang[2]:.2f}, "
          f"DIP {ang[3]:.2f} deg; keyframe settled at ctrl = 0, max loop error {e * 1e3:.4f} mm)")


# ---------------------------------------------------------------- 5-digit hand
def build_hand(design, dz):
    if DST.exists():
        shutil.rmtree(DST)
    (DST / "assets").mkdir(parents=True)
    tree = BF.parse(SRC_SLIM / "robot.xml")
    mj = tree.getroot()
    # ---- assets: copy every mesh file into DST/assets (self-contained)
    asset = mj.find("asset")
    seen = set()
    for el in list(asset):
        if el.tag != "mesh":
            continue
        src = (SRC_SLIM / "assets" / el.get("file")).resolve()
        name = el.get("name") or Path(el.get("file")).stem
        if name in seen:   # duplicated asset lines in the source
            asset.remove(el)
            continue
        seen.add(name)
        el.set("name", name)
        el.set("file", src.name)
        shutil.copy2(src, DST / "assets" / src.name)
    mats = set()
    for el in list(asset):
        if el.tag == "material":
            if el.get("name") in mats:
                asset.remove(el)
            mats.add(el.get("name"))
    extra = list(MESHES) + list(THUMB_MESHES) + ([PINKY_PREFIX + m[2:] for m in MESHES] if PINKY["suffix"] else [])
    for mesh in extra:
        shutil.copy2(stl(mesh), DST / "assets" / f"{mesh}.stl")
        ET.SubElement(asset, "mesh", name=mesh, file=f"{mesh}.stl", scale="0.001 0.001 0.001")
    add_materials(asset)
    # ---- fingers 1, 2, 3, 5
    angs = {}
    for N in (1, 2, 3, 5):
        horn = next(b for b in mj.iter("body") if any(j.get("name") == f"finger{N}_motor1" for j in b.findall("joint")))
        rod = next(b for b in horn if b.tag == "body")
        link = next(b for b in rod if b.tag == "body")
        if N == 5 and PINKY["suffix"]:
            angs[N] = convert_finger(mj, link, N, PINKY["design"], PINKY["dz"], suffix=f"_{N}", prefix=PINKY_PREFIX)
        else:
            angs[N] = convert_finger(mj, link, N, design, dz, suffix=f"_{N}")
    # ---- thumb (finger4): slim parts + styled pad set
    horn = next(b for b in mj.iter("body") if any(j.get("name") == "finger4_motor1" for j in b.findall("joint")))
    n_sw = 0
    for body in horn.iter("body"):
        geoms = list(body)
        for i, g in enumerate(geoms):
            if g.tag != "geom":
                continue
            mesh = g.get("mesh")
            if mesh == "proximal_shell":
                g.set("mesh", "thumb_proximal_shell")
                pad = ET.Element("geom", {"type": "mesh", "class": "visual", "pos": g.get("pos"), "quat": g.get("quat"),
                                          "mesh": "thumb_proximal_pad", "material": "uf_pad"})
                body.insert(list(body).index(g) + 1, pad)
                body.insert(list(body).index(g) + 1, ET.Comment(" Part thumb_proximal_pad (styled pad set) "))
                n_sw += 1
            elif mesh == "distal_shell":
                g.set("mesh", "thumb_distal_shell")
                n_sw += 1
            elif mesh == "distal_pad":
                g.set("mesh", "thumb_distal_pad")
                g.set("material", "uf_pad")
                n_sw += 1
    assert n_sw == 3, n_sw
    # drop meshes that are no longer used
    used = {g.get("mesh") for g in mj.iter("geom") if g.get("mesh")}
    for el in list(asset):
        if el.tag == "mesh" and el.get("name") not in used:
            (DST / "assets" / el.get("file")).unlink(missing_ok=True)
            asset.remove(el)
    ET.indent(tree, space="  ")
    body = ET.tostring(mj, encoding="unicode")
    header = ("<?xml version=\"1.0\" ?>\n<!-- Generated using onshape-to-robot -->\n"
              "<!-- Ultimate fingers: AH_Right_5F_Slim with index/middle/ring/pinky replaced by the thin styled 3-phalanx finger and the "
              "slim thumb with the styled pad set (cad/five_finger/ultimate_finger)"
              + (f"; pinky phalanges scaled x{PINKY['scale']:g} (meshes {PINKY_PREFIX}_*)" if PINKY["suffix"] else "")
              + ", by Demo/AHSimulation/ultimate_finger/build_models.py. Do not edit by hand. -->\n"
              "<!-- Onshape https://cad.onshape.com/documents/430ff184cf3dd9557aaff2be/w/e3658b7152c139971d22c688/e/a5789448a382c9e7e5c5750a -->\n"
              "<!-- 5-digit variant: finger5 (pinky) added by Demo/AHSimulation/five_finger/build_5f_model.py. -->\n")
    (DST / "robot.xml").write_text(header + body + "\n")
    for f in ("joints_properties.xml", "additional.xml"):
        shutil.copy2(SRC5 / f, DST / f)
    # palm/back shells and pads (scene_shells.xml): R-Top_Shell_5F, R-Palm_Shell_5F and every R-Palm_Pad_*_5F in SHELLS
    # (fitted to this hand by make_5f_shells.py --model AH_Right_5F_3S --out SHELLS); else the AH_Right_5F copies
    for f in (DST / "assets").glob("r_*_5f.stl"):
        if "hand_plate" not in f.name:
            f.unlink()
    own = ([SHELLS / "R-Top_Shell_5F.stl", SHELLS / "R-Palm_Shell_5F.stl"] + sorted(SHELLS.glob("R-Palm_Pad_*_5F.stl"))
           if SHELLS.is_dir() else [])
    if own and all(f.exists() for f in own):
        shell_meshes = []
        for f in own:
            name = "r_" + f.stem[2:].lower()            # R-Palm_Pad_Palm_5F -> r_palm_pad_palm_5f
            shutil.copy2(f, DST / "assets" / f"{name}.stl")
            shell_meshes.append(name)
        shell_src = SHELLS.relative_to(REPO) if SHELLS.is_relative_to(REPO) else SHELLS
    else:
        shell_meshes = []
        for f in sorted(SRC5.glob("assets/r_*_5f.stl")):
            if "hand_plate" in f.name:
                continue
            shutil.copy2(f, DST / "assets" / f.name)
            shell_meshes.append(f.stem)
        shell_src = f"{SRC5.relative_to(REPO)}/assets (no shells in {SHELLS}; these were fitted to the stock fingers)"
    print(f"  scene_shells.xml: {', '.join(shell_meshes)} from {shell_src}")
    # ---- keyframe: settle at the home ctrl (0; the thumb inside its command envelope) from qpos0 (the export pose:
    # every loop is closed by construction)
    (DST / "keyframes.xml").write_text("<mujoco><keyframe/></mujoco>\n")
    shutil.copy2(SRC5 / "scene.xml", DST / "scene.xml")
    m = mujoco.MjModel.from_xml_path(str(DST / "scene.xml"))
    d = mujoco.MjData(m)
    mujoco.mj_forward(m, d)
    d.ctrl[:] = home_ctrl(m)
    for _ in range(5000):
        mujoco.mj_step(m, d)
    assert np.all(np.isfinite(d.qpos))
    err = max(np.linalg.norm(d.site_xpos[m.eq_obj1id[i]] - d.site_xpos[m.eq_obj2id[i]]) for i in range(m.neq))
    (DST / "keyframes.xml").write_text("<mujoco>\n  <keyframe>\n    <key name=\"zero\"\n         qpos=\""
                                       + " ".join(f"{x:.6g}" for x in d.qpos) + "\"\n         />\n  </keyframe>\n</mujoco>\n")
    # ---- scenes: finger targets on the tips at the keyframe
    mujoco.mj_forward(m, d)
    text = (SRC5 / "scene.xml").read_text()
    for N in (1, 2, 3, 4, 5):
        s = m.site(f"tip{N}")
        q = np.zeros(4)
        mujoco.mju_mat2Quat(q, d.site_xmat[s.id])
        text, n = re.subn(rf'(<body name="finger{N}_target" )pos="[^"]*" quat="[^"]*"',
                          rf'\1pos="{fmt(d.site_xpos[s.id])}" quat="{fmt(q)}"', text)
        assert n == 1, N
    (DST / "scene.xml").write_text(text)
    # scene_shells.xml = scene.xml + the shells as static visual meshes in the plate's frame (as build_5f_model.py)
    plate = next(g for g in ET.parse(DST / "robot.xml").getroot().find("worldbody/body").findall("geom")
                 if g.get("mesh") == "r_hand_plate")
    rgba = {n: SHELL_RGBA["pad"] if "_pad_" in n else SHELL_RGBA["top_shell"] if "top_shell" in n else SHELL_RGBA["palm_shell"]
            for n in shell_meshes}
    block = ("    <asset>\n" + "\n".join(f'        <mesh name="{n}" file="{n}.stl" scale="0.001 0.001 0.001"/>' for n in shell_meshes)
             + "\n    </asset>\n\n    <worldbody>\n        <!-- palm/back shells and grip pads (static: the palm is fixed to the world) -->\n"
             + f'        <body name="shells" pos="{plate.get("pos")}" quat="{plate.get("quat")}">\n'
             + "\n".join(f'          <geom type="mesh" mesh="{n}" rgba="{rgba[n]}" contype="0" conaffinity="0" group="2"/>'
                         for n in shell_meshes) + "\n        </body>\n    </worldbody>\n")
    anchor = '    <include file="keyframes.xml"/>'
    assert anchor in text
    (DST / "scene_shells.xml").write_text(text.replace(anchor, block + anchor))
    m2 = mujoco.MjModel.from_xml_path(str(DST / "scene.xml"))
    m3 = mujoco.MjModel.from_xml_path(str(DST / "scene_shells.xml"))
    names = [mujoco.mj_id2name(m2, mujoco.mjtObj.mjOBJ_ACTUATOR, i) for i in range(m2.nu)]
    print(f"wrote {DST.relative_to(REPO)}: nbody {m2.nbody}, njnt {m2.njnt}, nq {m2.nq}, nu {m2.nu}, neq {m2.neq}, ngeom {m2.ngeom}, "
          f"nmesh {m2.nmesh}, nkey {m2.nkey}; scene_shells.xml compiles ({m3.ngeom} geoms); keyframe loop error "
          f"{err * 1e3:.4f} mm; actuators {names}")
    print("  export pose per converted finger (Link, MCP, PIP, DIP deg): "
          + "; ".join(f"finger{N} {np.round(a, 2).tolist()}" for N, a in angs.items()))


def main():
    global SHELLS
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--no-hand", action="store_true")
    ap.add_argument("--no-finger", action="store_true")
    ap.add_argument("--shells", type=Path, default=SHELLS, help="folder with R-Top_Shell_5F.stl, R-Palm_Shell_5F.stl, "
                    "R-Palm_Pad_*_5F.stl (default cad/five_finger/stl)")
    ap.add_argument("--pinky-scale", type=float, default=0.88,
                    help="phalanx length scale of the pinky (needs make_ultimate_finger.py --scale <s> first); 1 = same as the ring")
    args = ap.parse_args()
    SHELLS = args.shells.resolve()
    design, dz = load_design()
    if args.pinky_scale != 1.0:
        sfx = f"_S{int(round(args.pinky_scale * 100)):03d}"
        PINKY.update(scale=args.pinky_scale, suffix=sfx)
        PINKY["design"], PINKY["dz"] = load_design(sfx)
    MODEL_DIR.mkdir(parents=True, exist_ok=True)
    if not args.no_finger:
        build_stock()      # model/finger_stock.xml: the stock baseline for the checks (our own copy)
        build_finger(design, dz)
    if not args.no_hand:
        build_hand(design, dz)


if __name__ == "__main__":
    main()
