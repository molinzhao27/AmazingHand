#!/usr/bin/env python3
"""Generate the standalone one-finger MJCF models of the 3-segment study.

model/finger_stock.xml  the stock 2-phalanx index finger (finger1), cut out of AH_Right_5F:
                        palm plate, its two SCS0009 servos, finger frames, both motor chains,
                        the five loop-closure constraints and the two position actuators.
model/finger_3seg.xml   the same finger with the 3-phalanx design of cad/five_finger/three_segment
                        (design.json + the STLs written by make_three_segment.py): the stock servos,
                        horns, rods, gimbal and Link base are kept; the Link arm is new, the stock
                        Distal becomes the middle phalanx P2, plus a new proximal P1, distal P3 and
                        DIP coupler L2 with one more loop closure (L2 <-> P3).
model/hand5_3seg/       optional: the whole 5-digit right hand AH_Right_5F with index, middle, ring and pinky
                        converted the same way (thumb stock), generated from AH_Right_5F/mjcf/robot.xml
                        (robot.xml + scene.xml, same layout as AH_Right_5F/mjcf).
model/scene_*.xml       the above with a light and a floor-free background.

Stock meshes are referenced from AH_Right_5F/mjcf/assets, new meshes from the CAD folder, so the
sim and the CAD cannot drift apart. Nothing is hand-edited.

Usage: python build_finger_models.py [--stock-only] [--no-hand]
"""

import argparse
import copy
import json
import os
import xml.etree.ElementTree as ET

import mujoco
import numpy as np
import trimesh

from finger_common import (CAD_DIR, DESIGN_JSON, MODEL_DIR, SIM_5F, STOCK_NAMES, H, Hinv, flex, log, mat_of,
                           quat_of)  # noqa: F401

INDEX_FIXED = ["scs0009", "scs0009_4", "finger_frame_1", "finger_frame_2_4", "bushing_0608_04_2", "bushing_0608_04_6"]
CONTEXT = ["r_hand_plate", "r_wrist_interface"]
F1_SITES = ["closing_1 (1)_2", "closing_1 (1)_2_z"]
F1_BODIES = ["custom_servo_horn", "rotule_ball_2"]
PLA, TPU = 1240.0, 1210.0  # kg/m^3


def parse(path):
    return ET.parse(path, parser=ET.XMLParser(target=ET.TreeBuilder(insert_comments=True)))


def is_comment(el):
    return el.tag is ET.Comment


def part_geoms(body):
    out, children = {}, list(body)
    for c, nxt in zip(children, children[1:]):
        if is_comment(c) and c.text.strip().startswith("Part ") and nxt.tag == "geom":
            out[c.text.strip()[5:]] = nxt
    return out


def child(parent, tag, name):
    for el in parent:
        if el.tag == tag and el.get("name") == name:
            return el
    raise KeyError(name)


def fmt(v):
    return " ".join(f"{x:.9g}" for x in np.asarray(v, float).ravel())


def get_pose(el):
    pos = np.array([float(x) for x in el.get("pos", "0 0 0").split()])
    quat = np.array([float(x) for x in el.get("quat", "1 0 0 0").split()])
    return H(mat_of(quat / np.linalg.norm(quat)), pos)


def set_pose(el, T):
    el.set("pos", fmt(T[:3, 3]))
    el.set("quat", fmt(quat_of(T[:3, :3])))


def rel_from(model_dir, path):
    return os.path.relpath(path, model_dir)


# ---------------------------------------------------------------- stock extraction
def extract_stock():
    """ElementTree of the stock index finger as a standalone model (no file written)."""
    src = parse(SIM_5F / "robot.xml").getroot()
    root_src = src.find("worldbody/body")
    mj = ET.Element("mujoco", model="ah_finger_stock")
    mj.append(ET.Comment(" Generated by Demo/AHSimulation/three_segment/build_finger_models.py from AH_Right_5F "
                         "(index finger = finger1). Do not edit by hand. "))
    ET.SubElement(mj, "compiler", angle="radian", autolimits="true")
    for el in src:
        if el.tag == "default":
            mj.append(copy.deepcopy(el))
    wb = ET.SubElement(mj, "worldbody")
    ET.SubElement(wb, "light", pos="0 0 1", dir="0 0 -1", directional="true", diffuse="0.6 0.6 0.6")
    root = ET.SubElement(wb, "body", {k: v for k, v in root_src.attrib.items()})
    root.append(copy.deepcopy(root_src.find("inertial")))
    geoms = part_geoms(root_src)
    for name in INDEX_FIXED + CONTEXT:
        root.append(ET.Comment(f" Part {name} "))
        root.append(copy.deepcopy(geoms[name]))
    for name in F1_SITES:
        root.append(copy.deepcopy(child(root_src, "site", name)))
    for name in F1_BODIES:
        root.append(copy.deepcopy(child(root_src, "body", name)))

    act = ET.SubElement(mj, "actuator")
    for el in src.find("actuator"):
        if el.tag == "position" and el.get("name", "").startswith("finger1_"):
            act.append(copy.deepcopy(el))
    sites = {s.get("name") for s in root.iter("site")}
    eq = ET.SubElement(mj, "equality")
    for el in src.find("equality"):
        if el.tag == "connect" and el.get("site1") in sites:
            assert el.get("site2") in sites
            eq.append(copy.deepcopy(el))
    assert len(eq) == 5, len(eq)
    return mj


def finish_assets(mj, model_dir, extra_meshes=()):
    """Add <asset> with every mesh/material used (stock meshes from AH_Right_5F, extra ones as given)."""
    src = parse(SIM_5F / "robot.xml").getroot().find("asset")
    used_mesh = {g.get("mesh") for g in mj.iter("geom") if g.get("mesh")}
    used_mat = {g.get("material") for g in mj.iter("geom") if g.get("material")}
    asset = ET.Element("asset")
    extra_names = {e["name"] for e in extra_meshes}
    for el in src:
        if el.tag == "mesh":
            name = el.get("name") or os.path.splitext(el.get("file"))[0]
            if name in used_mesh and name not in extra_names:
                e = ET.SubElement(asset, "mesh", name=name, file=rel_from(model_dir, SIM_5F / "assets" / el.get("file")))
                if el.get("scale"):
                    e.set("scale", el.get("scale"))
        elif el.tag == "material" and el.get("name") in used_mat:
            asset.append(copy.deepcopy(el))
    for e in extra_meshes:
        ET.SubElement(asset, "mesh", name=e["name"], file=rel_from(model_dir, e["file"]), scale="0.001 0.001 0.001")
    for name, rgba in (("p_core", "0.86 0.86 0.86 1"), ("p_shell", "1 1 1 0.55"), ("p_link", "0.95 0.45 0.2 1"),
                       ("p_coupler", "0.2 0.55 0.95 1"), ("p_pin", "0.6 0.65 0.69 1")):
        if name in used_mat:
            ET.SubElement(asset, "material", name=name, rgba=rgba)
    i = list(mj).index(mj.find("worldbody"))
    mj.insert(i, asset)


def write_scene(name, model_file, model_dir, keyframe=None):
    s = ET.Element("mujoco", model=f"scene_{name}")
    ET.SubElement(s, "include", file=model_file)
    vis = ET.SubElement(s, "visual")
    ET.SubElement(vis, "headlight", diffuse="0.6 0.6 0.6", ambient="0.3 0.3 0.3", specular="0 0 0")
    ET.SubElement(vis, "global", azimuth="200", elevation="-15", offwidth="1920", offheight="1440")
    a = ET.SubElement(s, "asset")
    ET.SubElement(a, "texture", type="skybox", builtin="gradient", rgb1="0.3 0.5 0.7", rgb2="0 0 0",
                  width="512", height="3072")
    if keyframe is not None:
        k = ET.SubElement(s, "keyframe")
        ET.SubElement(k, "key", name="zero", qpos=fmt(keyframe))
    tree = ET.ElementTree(s)
    ET.indent(tree, space="  ")
    tree.write(model_dir / f"scene_{name}.xml")


def settle_keyframe(scene_path):
    m = mujoco.MjModel.from_xml_path(str(scene_path))
    d = mujoco.MjData(m)
    mujoco.mj_forward(m, d)
    for _ in range(1500):
        mujoco.mj_step(m, d)
    e = max(np.linalg.norm(d.site_xpos[m.eq_obj1id[i]] - d.site_xpos[m.eq_obj2id[i]]) for i in range(m.neq))
    return d.qpos.copy(), e


def write_model(mj, name):
    tree = ET.ElementTree(mj)
    ET.indent(tree, space="  ")
    path = MODEL_DIR / f"finger_{name}.xml"
    tree.write(path)
    write_scene(name, path.name, MODEL_DIR)
    q, e = settle_keyframe(MODEL_DIR / f"scene_{name}.xml")
    write_scene(name, path.name, MODEL_DIR, keyframe=q)
    log(f"wrote {path.relative_to(MODEL_DIR.parent)} and scene_{name}.xml (keyframe settled at ctrl=0, "
        f"max loop error {e * 1e3:.4f} mm)")
    return path


def build_stock():
    mj = extract_stock()
    mj.find("worldbody/body").find("body[@name='custom_servo_horn']")  # sanity
    finish_assets(mj, MODEL_DIR)
    return write_model(mj, "stock")


# ---------------------------------------------------------------- 3-segment model
def mass_props(stl_mm, density):
    """Mass (kg), CoM (m) and full inertia about the CoM (kg m^2) in the STL frame."""
    tm = trimesh.load(stl_mm)
    assert tm.is_watertight, stl_mm
    tm.apply_scale(1e-3)
    tm.density = density
    I = tm.moment_inertia
    return tm.mass, tm.center_mass, np.array([I[0, 0], I[1, 1], I[2, 2], I[0, 1], I[0, 2], I[1, 2]])


def add_inertial(body, items):
    """items: [(mass kg, com (3,) m, inertia about com (3, 3)) in the body frame] -> one <inertial>."""
    M = sum(i[0] for i in items)
    c = sum(mi * ci for mi, ci, _ in items) / M
    I = np.zeros((3, 3))
    for mi, ci, Ii in items:
        r = ci - c
        I += Ii + mi * (np.dot(r, r) * np.eye(3) - np.outer(r, r))
    body.insert(0, ET.Element("inertial", pos=fmt(c), mass=f"{M:.6g}",
                              fullinertia=fmt([I[0, 0], I[1, 1], I[2, 2], I[0, 1], I[0, 2], I[1, 2]])))
    return M


def mesh_item(stl_mm, density, T=None):
    mass, com, Iv = mass_props(stl_mm, density)
    Ic = np.array([[Iv[0], Iv[3], Iv[4]], [Iv[3], Iv[1], Iv[5]], [Iv[4], Iv[5], Iv[2]]])
    T = H() if T is None else T
    R = T[:3, :3]
    return mass, R @ com + T[:3, 3], R @ Ic @ R.T


def load_design():
    from linkage import Design  # planar kinematics of the design (same code the synthesis uses)

    design = json.loads(DESIGN_JSON.read_text())
    stl = {k: CAD_DIR / "stl" / v for k, v in design["cad"]["stl"].items()}
    return design, Design.from_json(design), stl


def convert_finger(mj, link, N, design, dz, stl, suffix=""):
    """Turn one stock finger (its Link body `link`, finger number N) into the 3-phalanx design, in place:
    new Link arm, P2 (old Distal's place), P1, P3, L2, the MCP closure sites on P1, the DIP-coupler
    closure, and the tip site tipN on P3."""
    from finger_common import xangle
    from linkage import O_L, O_M

    cad = design["cad"]
    gimbal = next(b for b in link if b.tag == "body" and any(g.get("mesh") == "gimbal" for g in b.iter("geom")))
    distal = next(b for b in link if b.tag == "body" and any(g.get("mesh") == "distal" for g in b.findall("geom")))
    mm = 1e-3

    def P(yz, x=0.0):
        return np.array([x, yz[0], yz[1]]) * mm

    # poses of the stock CAD frames in the Link body at qpos = 0 (the onshape export pose)
    lg = next(g for g in link if g.tag == "geom" and g.get("mesh") == "link")
    T_lb_lcad = get_pose(lg)
    gg = next(g for g in gimbal if g.tag == "geom" and g.get("mesh") == "gimbal")
    T_lb_gcad = get_pose(gimbal) @ get_pose(gg)
    T_g_l = Hinv(T_lb_gcad) @ T_lb_lcad  # Link CAD frame in the gimbal CAD frame
    psi_export = xangle(T_g_l[:3, :3])
    OL3 = P(O_L)
    assert np.allclose(T_g_l[:3, :3], flex(psi_export), atol=1e-5), "Link is not a pure rotation about x"
    dx = T_g_l[:3, 3] - (OL3 - flex(psi_export) @ OL3)  # the Link CAD frame sits off the gimbal mid-plane in x
    assert abs(dx[1]) < 2e-6 and abs(dx[2]) < 2e-6, "Link does not rotate about O_L"
    assert abs(dx[0] * 1e3 - cad["lateral_offset_mm"]["link_and_new_parts"]) < 1e-3, dx
    DX = H(np.eye(3), np.array([dx[0], 0, 0]))  # every new part is drawn on the Link mid-plane
    sol = dz.solve_psi(psi_export)
    assert sol is not None
    th1, th2, th3, l2r = sol["mcp"], sol["pip"], sol["dip"], sol["l2"]
    log(f"finger{N}: export pose (qpos = 0): Link angle psi {np.degrees(psi_export):.3f} deg -> MCP {np.degrees(th1):.2f}, "
        f"PIP {np.degrees(th2):.2f}, DIP {np.degrees(th3):.2f} deg")

    def about(R, pivot_straight, pivot_now):
        return H(R, pivot_now - R @ pivot_straight)

    T_g = dict(p1=DX @ H(flex(th1)))
    T_g["p2"] = about(flex(th1 + th2), P(dz.PIP0), (T_g["p1"] @ np.r_[P(dz.PIP0), 1])[:3])
    T_g["p3"] = about(flex(th1 + th2 + th3), P(dz.DIP0), (T_g["p2"] @ np.r_[P(dz.DIP0), 1])[:3])
    T_g["l2"] = about(flex(th1 + l2r), P(dz.A0), (T_g["p1"] @ np.r_[P(dz.A0), 1])[:3])
    # loop closures at qpos = 0
    P4L = np.array(design["geometry"]["P4_in_link_frame"])
    e_p4 = np.linalg.norm((T_g_l @ np.r_[P(P4L), 1])[:3] - (T_g["p2"] @ np.r_[P(dz.P4_0), 1])[:3])
    e_b = np.linalg.norm((T_g["l2"] @ np.r_[P(dz.B0), 1])[:3] - (T_g["p3"] @ np.r_[P(dz.B0), 1])[:3])
    assert e_p4 < 1e-7 and e_b < 1e-7, (e_p4, e_b)

    # Link: stock base + new arm, same frame as the stock Link mesh
    lg.set("mesh", "link3s")
    lg.set("material", "p_link")
    link.remove(link.find("inertial"))
    studs = 0.5 * (0.00277119 - 0.0019275)  # stock Link body mass minus the stock Link part = studs + screws, per side
    items = [mesh_item(stl["link3s"], PLA, T_lb_lcad)]
    for sx in (-8.05, 8.05):
        items.append((studs, (T_lb_lcad @ np.r_[P([3.596, -11.051], sx), 1])[:3], np.eye(3) * 1e-10))
    add_inertial(link, items)

    # remove the stock distal (and the proximal below it)
    for c in [c for c in link if is_comment(c) and "parallel_pin_2_x_10" in (c.text or "")]:
        link.remove(c)
    link.remove(distal)

    def add_geoms(body, keys):
        for key in keys:
            mat = "p_shell" if ("shell" in key or "pad" in key) else "p_coupler" if key == "l2" else "p_core"
            ET.SubElement(body, "geom", {"class": "visual", "type": "mesh", "mesh": key, "material": mat})

    def add_pin(body, yz, half):
        ET.SubElement(body, "geom", {"class": "visual", "type": "cylinder", "size": f"0.001 {half * mm:.4g}",
                                     "pos": fmt(P(yz)), "quat": "0.7071068 0 0.7071068 0", "material": "p_pin"})

    def dens(key):
        return TPU if ("shell" in key or "pad" in key) else PLA

    bodies = cad["bodies"]
    link.append(ET.Comment(f" 3-phalanx finger{N}: P2 (middle) on the Link at P4, P1 (proximal) on P2 at the PIP, "
                           f"L2 (DIP coupler) on P1 at A, P3 (distal) on P2 at the DIP "))
    # P2 (middle) under the Link, hinge at P4: the stock joint name passive4 (N)
    p2 = ET.SubElement(link, "body", name=f"p2{suffix}")
    set_pose(p2, T_lb_gcad @ T_g["p2"])
    ET.SubElement(p2, "joint", name=f"passive4 ({N})", type="hinge", axis="1 0 0", pos=fmt(P(dz.P4_0)))
    add_geoms(p2, bodies["p2"])
    add_pin(p2, dz.P4_0, 5.0)
    # P1 (proximal) under P2, hinge at the PIP: the stock joint name passive_5 (N)
    p1 = ET.SubElement(p2, "body", name=f"p1{suffix}")
    set_pose(p1, Hinv(T_g["p2"]) @ T_g["p1"])
    ET.SubElement(p1, "joint", name=f"passive_5 ({N})", type="hinge", axis="1 0 0", pos=fmt(P(dz.PIP0)))
    add_geoms(p1, bodies["p1"])
    for yz in (O_M, dz.PIP0, dz.A0):
        add_pin(p1, yz, 8.0)
    T_p1cad_gb = Hinv(DX) @ Hinv(get_pose(gg))  # gimbal body -> P1 frame in the straight pose
    for end in ("", "_z"):
        p_cad = (T_p1cad_gb @ np.r_[get_pose(child(gimbal, "site", f"closing_3 ({N})_2{end}"))[:3, 3], 1])[:3]
        ET.SubElement(p1, "site", name=f"closing_3 ({N})_1{end}", pos=fmt(p_cad), group="3")
    # L2 (DIP coupler) under P1, hinge at A
    l2 = ET.SubElement(p1, "body", name=f"l2{suffix}")
    set_pose(l2, Hinv(T_g["p1"]) @ T_g["l2"])
    ET.SubElement(l2, "joint", name=f"coupler_a ({N})", type="hinge", axis="1 0 0", pos=fmt(P(dz.A0)))
    add_geoms(l2, bodies["l2"])
    ET.SubElement(l2, "site", name=f"closing_dip ({N})_1", pos=fmt(P(dz.B0)), group="3")
    # P3 (distal) under P2, hinge at the DIP
    p3 = ET.SubElement(p2, "body", name=f"p3{suffix}")
    set_pose(p3, Hinv(T_g["p2"]) @ T_g["p3"])
    ET.SubElement(p3, "joint", name=f"dip ({N})", type="hinge", axis="1 0 0", pos=fmt(P(dz.DIP0)))
    add_geoms(p3, bodies["p3"])
    for yz in (dz.DIP0, dz.B0):
        add_pin(p3, yz, 8.0)
    ET.SubElement(p3, "site", name=f"closing_dip ({N})_2", pos=fmt(P(dz.B0)), group="3")
    ET.SubElement(p3, "site", name=f"tip{N}", pos=fmt(P(dz.TIP0)), group="3")

    for body, key in ((p1, "p1"), (p2, "p2"), (p3, "p3"), (l2, "l2")):
        add_inertial(body, [mesh_item(stl[k], dens(k)) for k in bodies[key]])
    mj.find("equality").append(ET.Element("connect", site1=f"closing_dip ({N})_1", site2=f"closing_dip ({N})_2"))


def build_3seg():
    design, dz, stl = load_design()
    mj = extract_stock()
    mj.set("model", "ah_finger_3seg")
    mj[0].text = (" Generated by Demo/AHSimulation/three_segment/build_finger_models.py: the index finger of AH_Right_5F "
                  "with the 3-phalanx design of cad/five_finger/three_segment (design.json + STLs). Do not edit by hand. ")
    link = next(b for b in mj.iter("body") if b.get("name") == STOCK_NAMES["link"])
    convert_finger(mj, link, 1, design, dz, stl)
    finish_assets(mj, MODEL_DIR, [dict(name=k, file=v) for k, v in stl.items()])
    return write_model(mj, "3seg")


def build_hand5_3seg():
    """The 5-digit right hand AH_Right_5F with index, middle, ring and pinky converted (thumb stock)."""
    design, dz, stl = load_design()
    src = parse(SIM_5F / "robot.xml").getroot()
    mj = ET.Element("mujoco", model="ah_right_5f_3seg")
    mj.append(ET.Comment(" Generated by Demo/AHSimulation/three_segment/build_finger_models.py from AH_Right_5F: index, "
                         "middle, ring and pinky with the 3-phalanx design (cad/five_finger/three_segment), thumb stock. "
                         "Do not edit by hand. "))
    ET.SubElement(mj, "compiler", angle="radian", autolimits="true")
    for el in src:
        if el.tag in ("default", "worldbody", "actuator", "equality", "contact"):
            mj.append(copy.deepcopy(el))
    wb = mj.find("worldbody")
    wb.insert(0, ET.Element("light", pos="0 0 1", dir="0 0 -1", directional="true", diffuse="0.6 0.6 0.6"))
    for N in (1, 2, 3, 5):
        jname = f"finger{N}_motor1"
        horn = next(b for b in mj.iter("body") if any(j.get("name") == jname for j in b.findall("joint")))
        rod = next(b for b in horn if b.tag == "body")
        link = next(b for b in rod if b.tag == "body")
        convert_finger(mj, link, N, design, dz, stl, suffix=f"_{N}")
    out_dir = MODEL_DIR / "hand5_3seg"  # robot.xml + scene.xml, the layout of AH_Right_5F/mjcf (verify_5f_model.Hand)
    out_dir.mkdir(parents=True, exist_ok=True)
    finish_assets(mj, out_dir, [dict(name=k, file=v) for k, v in stl.items()])
    tree = ET.ElementTree(mj)
    ET.indent(tree, space="  ")
    path = out_dir / "robot.xml"
    tree.write(path)
    write_scene("hand5_3seg", path.name, out_dir)
    q, e = settle_keyframe(out_dir / "scene_hand5_3seg.xml")
    write_scene("hand5_3seg", path.name, out_dir, keyframe=q)
    (out_dir / "scene_hand5_3seg.xml").rename(out_dir / "scene.xml")
    log(f"wrote {out_dir.relative_to(MODEL_DIR.parent)}/robot.xml and scene.xml (keyframe settled at ctrl=0, "
        f"max loop error {e * 1e3:.4f} mm)")
    return path


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--stock-only", action="store_true")
    ap.add_argument("--no-hand", action="store_true", help="skip the 5-digit hand variant")
    args = ap.parse_args()
    MODEL_DIR.mkdir(parents=True, exist_ok=True)
    build_stock()
    if not args.stock_only:
        build_3seg()
        if not args.no_hand:
            build_hand5_3seg()


if __name__ == "__main__":
    main()
