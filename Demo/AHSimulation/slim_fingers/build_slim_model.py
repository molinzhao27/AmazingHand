#!/usr/bin/env python3
"""Generate AH_Right_5F_Slim/mjcf: the 5-digit right hand with the slim finger parts.

Starts from AH_Right_5F/mjcf (generated by five_finger/build_5f_model.py) and changes only the finger
parts; bodies, joints, sites, equality constraints, actuators and the keyframe are untouched, so the
kinematics are identical. In every digit:

  * the meshes proximal, proximal_shell, distal, distal_shell are replaced by the slim parts from
    cad/five_finger/slim_fingers/stl (mm, same part frames, loaded with scale 0.001); the mesh names
    stay the same, so every geom keeps its mesh reference;
  * a grip pad geom (distal_pad, grey) is added next to every distal_shell geom (same frame);
  * the 4 shell screws (std00447 ... M2.5x6) become M2.5x5 (mesh thermo_screw_m2_5x5: the M2.5x6
    with the shank shortened by 1 mm) and are moved inwards along their axis so that their heads sit
    in the slim shells' screw cups (head top |x| from design.json);
  * the proximal_shell geom gets exactly the frame of the proximal geom: the stock assembly has the
    shell 0.1 mm off-centre laterally, the slim shell is designed concentric with the core (it is
    located by its screw cups in the core's spot faces).

Meshes that do not change are referenced from AH_Right_5F/mjcf/assets (no copies), the slim meshes
are written to AH_Right_5F_Slim/mjcf/assets. scene.xml and scene_shells.xml (palm/back shells and
pads) are copied from AH_Right_5F with their mesh paths adjusted. Inertial properties are not
changed (every body has an explicit <inertial>; the slim parts are a few tenths of a gram lighter).

Usage: .venv/bin/python Demo/AHSimulation/slim_fingers/build_slim_model.py
"""

import json
import re
import shutil
from pathlib import Path

import mujoco
import numpy as np
import trimesh

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
SIM = HERE.parent / "AHSimulation"
SRC = SIM / "AH_Right_5F" / "mjcf"
DST = SIM / "AH_Right_5F_Slim" / "mjcf"
CAD = REPO / "cad" / "five_finger" / "slim_fingers"
STOCK_REL = "../../../AH_Right_5F/mjcf/assets/"   # from AH_Right_5F_Slim/mjcf/assets to the stock assets

SLIM = {"proximal": "Proximal_Slim", "proximal_shell": "Proximal_Shell_Slim",
        "distal": "Distal_Slim", "distal_shell": "Distal_Shell_Slim"}
PAD = ("distal_pad", "Distal_Pad_Slim")
PAD_RGBA = "0.07 0.07 0.08 1"
SCREW6 = "std00447_thermoplastique_m2_5x6__configuration_default"
SCREW5 = "thermo_screw_m2_5x5"


def q2m(q):
    m = np.zeros(9)
    mujoco.mju_quat2Mat(m, np.array(q, float))
    return m.reshape(3, 3)


def vec(s):
    return np.array([float(v) for v in s.split()])


def fmt(v):
    return " ".join(f"{x:.9g}" for x in v)


def screw5_mesh(path):
    """M2.5x5 from the model's M2.5x6 (metres): shank (z > head) scaled from 6.05 to 5.05 mm."""
    m = trimesh.load(SRC / "assets" / f"{SCREW6}.stl")
    v = m.vertices.copy()
    head = 1.55e-3
    sh = v[:, 2] > head + 5e-5
    v[sh, 2] = head + (v[sh, 2] - head) * (5.05 / 6.05)
    trimesh.Trimesh(v, m.faces, process=False).export(path)


def main():
    design = json.loads((CAD / "design.json").read_text())
    head_x = {"proximal": design["prox_screw_head_x"], "distal": design["dist_screw_head_x"]}
    if DST.exists():
        shutil.rmtree(DST)
    (DST / "assets").mkdir(parents=True)
    for f in SRC.glob("*.xml"):
        shutil.copy(f, DST / f.name)
    for mesh, part in list(SLIM.items()) + [PAD]:
        shutil.copy(CAD / "stl" / f"{part}.stl", DST / "assets" / f"{mesh}_slim.stl")
    screw5_mesh(DST / "assets" / f"{SCREW5}.stl")

    xml = (DST / "robot.xml").read_text()
    xml = xml.replace("<!-- Generated using onshape-to-robot -->",
                      "<!-- Generated using onshape-to-robot -->\n<!-- Slim fingers: AH_Right_5F with the finger parts of "
                      "cad/five_finger/slim_fingers, by Demo/AHSimulation/slim_fingers/build_slim_model.py. Do not edit by hand. -->", 1)

    # ---- assets: stock meshes by relative path, slim meshes local (mm -> scale)
    def asset_line(mo):
        attrs = dict(re.findall(r'(\w+)="([^"]*)"', mo.group(1)))
        stem = Path(attrs["file"]).stem
        name = attrs.get("name", stem)
        if name in SLIM:
            return f'<mesh name="{name}" file="{name}_slim.stl" scale="0.001 0.001 0.001"/>'
        attrs["file"] = STOCK_REL + attrs["file"]
        return "<mesh " + " ".join(f'{k}="{v}"' for k, v in attrs.items()) + "/>"
    xml, n = re.subn(r"<mesh ([^>]*)/>", asset_line, xml)
    extra = (f'    <mesh name="{PAD[0]}" file="{PAD[0]}_slim.stl" scale="0.001 0.001 0.001"/>\n'
             f'    <mesh name="{SCREW5}" file="{SCREW5}.stl"/>\n'
             f'    <material name="{PAD[0]}_material" rgba="{PAD_RGBA}"/>\n  </asset>')
    xml = xml.replace("  </asset>", extra, 1)

    # ---- per body: shell frame = core frame, pad geom, screws M2.5x5 moved inwards
    lines = xml.split("\n")
    out = []
    geom_re = re.compile(r'^(\s*)<geom type="mesh" class="visual" pos="([^"]+)" quat="([^"]+)" mesh="([^"]+)" material="([^"]+)"/>$')
    # first pass: collect, per body block, the geoms (body = lines between a <body ...> and its first child <body or </body>)
    body_geoms, cur = {}, None
    for k, ln in enumerate(lines):
        if re.match(r"^\s*<body ", ln):
            cur = k
            body_geoms[cur] = []
        elif re.match(r"^\s*</body>", ln):
            cur = None
        mo = geom_re.match(ln)
        if mo and cur is not None:
            body_geoms[cur].append((k, mo))
    edits, inserts = {}, {}
    moved = {"proximal": 0, "distal": 0}
    for start, gl in body_geoms.items():
        meshes = {mo.group(4): (k, mo) for k, mo in gl}
        for core in ("proximal", "distal"):
            if core not in meshes:
                continue
            kc, mc = meshes[core]
            pos_c, R_c = vec(mc.group(2)), q2m(vec(mc.group(3)))
            if core == "proximal":
                ks, ms = meshes["proximal_shell"]
                assert np.allclose(vec(ms.group(3)), vec(mc.group(3)), atol=1e-5)
                edits[ks] = f'{ms.group(1)}<geom type="mesh" class="visual" pos="{mc.group(2)}" quat="{ms.group(3)}" mesh="proximal_shell" material="{ms.group(5)}"/>'
            else:
                ks, ms = meshes["distal_shell"]
                inserts[ks] = [f"{ms.group(1)}<!-- Part distal_pad (slim fingers: fingertip grip pad) -->",
                               f'{ms.group(1)}<geom type="mesh" class="visual" pos="{ms.group(2)}" quat="{ms.group(3)}" mesh="{PAD[0]}" material="{PAD[0]}_material"/>']
            for k, mo in gl:
                if mo.group(4) != SCREW6:
                    continue
                p = vec(mo.group(2))
                part = R_c.T @ (p - pos_c) * 1e3          # screw origin (head top) in the core's part frame, mm
                axis = R_c.T @ q2m(vec(mo.group(3)))[:, 2]  # screw axis in the part frame
                assert abs(abs(axis[0]) - 1) < 1e-3 and np.sign(axis[0]) == -np.sign(part[0]), (core, part, axis)
                part[0] = np.sign(part[0]) * head_x[core]
                new = pos_c + R_c @ part * 1e-3
                edits[k] = f'{mo.group(1)}<geom type="mesh" class="visual" pos="{fmt(new)}" quat="{mo.group(3)}" mesh="{SCREW5}" material="{mo.group(5)}"/>'
                moved[core] += 1
    for k, ln in enumerate(lines):
        if k in edits:
            prev = out[-1] if out else ""
            if "<!-- Part std00447" in prev:
                out[-1] = prev.replace("-->", "(M2.5x5, slim fingers) -->")
            out.append(edits[k])
        else:
            out.append(ln)
        if k in inserts:
            out.extend(inserts[k])
    xml = "\n".join(out)
    assert moved == {"proximal": 10, "distal": 10}, moved
    (DST / "robot.xml").write_text(xml)

    # scene_shells.xml: palm/back shell meshes from the stock assets
    sx = (DST / "scene_shells.xml").read_text()
    sx = re.sub(r'file="(r_[a-z_0-9]+\.stl)"', lambda mo: f'file="{STOCK_REL}{mo.group(1)}"', sx)
    (DST / "scene_shells.xml").write_text(sx)

    # sanity: compiles, same structure as the source model
    a = mujoco.MjModel.from_xml_path(str(SRC / "scene.xml"))
    b = mujoco.MjModel.from_xml_path(str(DST / "scene.xml"))
    c = mujoco.MjModel.from_xml_path(str(DST / "scene_shells.xml"))
    for attr in ("nbody", "njnt", "nq", "nu", "neq", "nsite", "nkey"):
        assert getattr(a, attr) == getattr(b, attr), attr
    assert b.ngeom == a.ngeom + 5 and np.allclose(a.body_pos, b.body_pos) and np.allclose(a.key_qpos, b.key_qpos)
    print(f"wrote {DST.relative_to(REPO)}: {b.nbody} bodies, {b.njnt} joints, {b.nu} actuators, {b.ngeom} geoms "
          f"(+5 pads), screws moved {moved}; scene_shells.xml compiles ({c.ngeom} geoms)")


if __name__ == "__main__":
    main()
